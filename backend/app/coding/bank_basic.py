def make(key, title, level, tags, story, task, inp, out, limits, cases, solve, hidden, code, families=(), source=None) -> Template:
    p = LEVELS[level]
    return Template(key, title, p.difficulty, statement(story, task, inp, out, limits), tuple(c[0] for c in cases), solve, hidden,
                    time_limit_ms=p.run_ms, notes=tuple(c[2] for c in cases), level=level, tags=tuple(tags), starter=code,
                    expected=tuple(c[1] for c in cases), families=tuple(families), source=source or source_of())


def _ints(n: int, lo: int, hi: int, rnd: random.Random) -> list[int]:
    return [rnd.randint(lo, hi) for _ in range(n)]


def _word(rnd: random.Random, n: int, alpha: str = LOWER) -> str:
    return "".join(rnd.choice(alpha) for _ in range(n))


def _n_arr(a) -> str:
    return _ln(len(a), _arr(a))


def _hid(fixed: list[str], gen) -> "callable":
    def hidden(rnd: random.Random) -> list[str]:
        return [*fixed, *gen(rnd)]
    return hidden


