def _keys_map(r: random.Random, h: int, w: int) -> list[str]:
    g = [list(x) for x in _cells(r, h, w, "......#")]
    spots = r.sample([(y, x) for y in range(h) for x in range(w)], 6)
    for (y, x), c in zip(spots, "SEaAbB"):
        g[y][x] = c
    return ["".join(x) for x in g]


