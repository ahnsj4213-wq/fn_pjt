def _edges(rows) -> list[str]:
    return [" ".join(map(str, e)) for e in rows]


def _graph(n: int, edges: list[tuple]) -> str:
    return _ln(f"{n} {len(edges)}", *_edges(edges))


def _rand_edges(r: random.Random, n: int, m: int, weight: int = 0) -> list[tuple]:
    out = []
    for _ in range(m):
        a = r.randint(1, n)
        b = r.randint(1, n - 1) if n > 1 else a
        b = b + 1 if b >= a else b
        out.append((a, b, r.randint(1, weight)) if weight else (a, b))
    return out


def _tree_parents(r: random.Random, n: int, deep: bool = False) -> list[int]:
    return [i - 1 if deep else r.randint(1, i - 1) for i in range(2, n + 1)]


def _cells(r: random.Random, h: int, w: int, chars: str) -> list[str]:
    return ["".join(r.choice(chars) for _ in range(w)) for _ in range(h)]


def _grid(g: list[str]) -> str:
    return _ln(f"{len(g)} {len(g[0])}", *g)


